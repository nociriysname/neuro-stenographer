out = pathlib.Path('raw_pod'); out.mkdir(exist_ok=True)
def run(batch):
    f = out / f"p{batch[0]['id']:05d}.json"
    if f.exists(): return f.name, 'cached'
    desc = "\n".join(f"id={s['id']}: сфера — {s['domain']}; формат — {s['type']}; спикеров — {s['speakers']}; длина — {s['length'][0]} ({s['length'][1]}); "
                     f"итог — {s['outcome']}; имена {'звучат' if s['names'] else 'не звучат'}; шум распознавания — {s['noise']}" for s in batch)
    tail = "\n\nВерни JSON {\"items\": [...]} — по одному элементу на сценарий, id как в сценарии. Диалоги должны сильно отличаться друг от друга по лексике и ходу разговора."
    err = ''
    for _ in range(3):
        r = subprocess.run(["codex", "exec", "-m", "gpt-6.1-sol", "-c", "model_reasoning_effort=medium", "-c", "service_tier=fast",
                            "--skip-git-repo-check", "-s", "read-only", "--ephemeral", "--output-schema", "schema.json",
                            "-o", str(f) + ".tmp", "-"], input=INSTR + desc + tail, text=True, capture_output=True, timeout=900)
        try:
            j = json.loads(pathlib.Path(str(f) + ".tmp").read_text())
            if sorted(x['id'] for x in j['items']) == [s['id'] for s in batch]:
                for x in j['items']: x['scenario'] = next(s for s in batch if s['id'] == x['id'])
                f.write_text(json.dumps(j, ensure_ascii=False)); return f.name, 'ok'
            err = 'ids mismatch'
        except Exception as e: err = f'{e} | {r.stderr[-200:]}'
    return f.name, 'FAIL ' + err
